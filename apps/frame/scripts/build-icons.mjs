// Builds src/core/icons.js from Lucide (https://lucide.dev, ISC license): only the icons the
// dashboard uses, under the short names the code asks for. Run after changing the list:
//   npm run icons -w @noor-frame/frame

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// our name -> Lucide name
const ICONS = {
  home: 'house', calendar: 'calendar', moonstar: 'moon-star', settings: 'settings',
  wifi: 'wifi', wifioff: 'wifi-off', clock: 'clock', bell: 'bell', check: 'check', x: 'x',
  left: 'chevron-left', right: 'chevron-right', plus: 'plus', minus: 'minus', undo: 'rotate-ccw',
  play: 'play', pause: 'pause', volume: 'volume-2', mute: 'volume-x', book: 'book-open',
  pin: 'map-pin', person: 'user', drop: 'droplet',
  car: 'car', walk: 'footprints', bike: 'bike', bus: 'bus-front',
  sun: 'sun', moon: 'moon', partly: 'cloud-sun', cloud: 'cloud', rain: 'cloud-rain',
  snow: 'cloud-snow', storm: 'cloud-lightning', fog: 'cloud-fog',
};

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(path.dirname(createRequire(import.meta.url).resolve('lucide-static/package.json')), 'icons');
const version = JSON.parse(readFileSync(path.join(dir, '..', 'package.json'), 'utf8')).version;

const out = {};
for (const [name, lucide] of Object.entries(ICONS)) {
  const svg = readFileSync(path.join(dir, lucide + '.svg'), 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  out[name] = inner.replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>').trim();
}

const body = Object.entries(out).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(path.join(here, '../src/core/icons.js'), `// Generated by scripts/build-icons.mjs from lucide-static ${version}. Do not edit by hand.
// Icons: Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors.
export const ICONS = {
${body}
};
`);
console.log(`wrote ${Object.keys(out).length} icons`);
